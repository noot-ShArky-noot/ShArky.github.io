#include <stdio.h>
#include <stdlib.h>

int main() {
    int rgb[3][4][5] ={{{247, 67, 32, 187, 240},
                        {122, 41, 21, 16, 154},
                        {52, 35, 79, 21, 93},
                        {27, 22, 35, 154, 75}},
                       {{14, 145, 132, 25, 40},
                        {212, 221, 121, 54, 14},
                        {132, 235, 178, 19, 14},
                        {122, 122, 133, 54, 47}},
                       {{17, 44, 32, 127, 240},
                        {22, 231, 21, 156, 124},
                        {32, 35, 78, 21, 194},
                        {127, 22, 33, 54, 45}}};
    
    int i, j, k;
    for (i=0; i<3; i++) {
        for (j=0; j<4; j++) {
            for (k=0; k<5; k++) {
                printf("%d ", rgb[i][j][k]); 
            }
            printf("\n");
        }
        printf("\n");
    }
    for (i=0; i<4; i++) {
        for (j=0; j<5; j++) {
            rgb[0][i][j]+=30;
            if (rgb[0][i][j]>255) {
                rgb[0][i][j]=255;
            }
            printf("%d ", rgb[0][i][j]);
        }
        printf("\n");
    }
    printf("\n");
    for (i=0; i<4; i++) {
        for (j=0; j<5; j++) {
            rgb[1][i][j]-=30;
            if (rgb[1][i][j]<0) {
                rgb[1][i][j]=0;
            }
            printf("%d ", rgb[1][i][j]);
        }
        printf("\n");
    }
}
